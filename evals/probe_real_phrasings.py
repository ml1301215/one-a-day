def main() -> int:
    strict = "--strict" in sys.argv
    fails: list[tuple[str, str, str, str]] = []
    print(f"{'期望':<4}{'实际':<4}{'判定':<4}说明 / 句子")
    print("-" * 78)
    for expect, label, text in CASES:
        v = classify(text)
        ok = v.level == expect
        if not ok:
            fails.append((expect, v.level, label, text))
        mark = "ok  " if ok else "FAIL"
        print(f"{expect:<4}{v.level:<4}{mark:<4}{label:<10}{text}")
        if not ok:
            print(f"{'':<16}命中={v.categories or '无'} 理由={v.reasons or '无'}")

    print("-" * 78)
    total = len(CASES)
    print(f"共 {total} 条，漏/错 {len(fails)} 条，准确率 {(total - len(fails)) / total:.1%}")
    if fails:
        print("\n问题清单：")
        for expect, got, label, text in fails:
            print(f"  [{label}] 期望 {expect} 实得 {got} → {text}")
    return 1 if (fails and strict) else 0


if __name__ == "__main__":
    raise SystemExit(main())
