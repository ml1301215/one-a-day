    r"(活|活着)(着)?(真|太|很)?(没意思|没意义|没什么意思|没劲)",
    r"(不如|干脆)(去)?死(了|掉)?(算了|吧)?",
    r"(结束|了结)(自己|我的生命|这条命)",
    r"(跳|从).{0,6}(楼|桥|河|江|天台).{0,4}(下去|跳)",
