"""安全规则库。

设计约束（来自方案 07）：
  1. 误判宁严不宽。把 L0 误判成 L2，代价是无聊一次；
     把 L3 误判成 L0，代价是产品事故。
  2. 但也不能把所有口语夸张都当危机——「累死了」「笑死了」是日常语法，
     处理方式是：先剥离口语夸张，再判断剩下的是不是真的求助。
  3. 中文没有空格，正则要覆盖「我 不想 活 了」这类插入与变体。
"""

