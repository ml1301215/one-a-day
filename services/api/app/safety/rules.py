# ---------------------------------------------------------------------------
# 依赖信号：把 AI 当唯一出口，需要引导向真人
# ---------------------------------------------------------------------------
DEPENDENCY_PATTERNS = [
    r"(只有你|就你能|你是唯一)(懂|理解|在乎|陪)",
    r"(不想|不愿)(和|跟)(任何人|别人|真人)(说话|聊)",
    r"(你比)(人|他们|所有人)(好|懂我)",
]

_SENTENCE_SPLIT = re.compile(r"[。！？!?；;\n]+")


@dataclass
class RuleHit:
    category: str
    pattern: str
    text: str


@dataclass
class RuleScan:
    hits: list[RuleHit] = field(default_factory=list)

    def has(self, *categories: str) -> bool:
        return any(h.category in categories for h in self.hits)

    def categories(self) -> list[str]:
        seen: list[str] = []
        for h in self.hits:
            if h.category not in seen:
                seen.append(h.category)
        return seen

    def matched(self, category: str) -> str | None:
        for h in self.hits:
            if h.category == category:
                return h.text
        return None


def _strip_colloquial(text: str) -> str:
    out = text
    for pat in COLLOQUIAL_EXAGGERATION:
        out = re.sub(pat, "　", out)
    return out


def _scan(text: str, patterns: list[str], category: str, hits: list[RuleHit]) -> None:
    for pat in patterns:
        m = re.search(pat, text)
        if m:
            hits.append(RuleHit(category=category, pattern=pat, text=m.group(0)))


def scan(text: str) -> RuleScan:
    """对单条用户输入做全量规则扫描。"""
    hits: list[RuleHit] = []
    raw = text.strip()
    if not raw:
        return RuleScan(hits=hits)

    # 危机与医疗/法律/未成年用原文扫（不剥离，避免漏判）
    _scan(raw, CRISIS_PATTERNS, "crisis", hits)
    _scan(raw, MEDICAL_PATTERNS, "medical", hits)
    _scan(raw, LEGAL_PATTERNS, "legal", hits)
    _scan(raw, MINOR_PATTERNS, "minor", hits)

    # 情绪类先剥离口语夸张，降低误报
    softened = _strip_colloquial(raw)
    for pat, cat in BOUNDARY_PROBES:
        m = re.search(pat, softened)
        if m:
            hits.append(RuleHit(category=f"probe:{cat}", pattern=pat, text=m.group(0)))

    _scan(softened, LOW_MOOD_PATTERNS, "low_mood", hits)
    _scan(softened, DEPENDENCY_PATTERNS, "dependency", hits)
    _scan(softened, NEGATIVE_PATTERNS, "negative", hits)

    return RuleScan(hits=hits)


def split_sentences(text: str) -> list[str]:
    return [s for s in _SENTENCE_SPLIT.split(text) if s.strip()]
